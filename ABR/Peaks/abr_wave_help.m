function abr_wave_help(parent_fig)
%ABR_WAVE_HELP  Help window for the ABR peak editor: chinchilla Waves I–V.
%   Text follows ASD-STE100 Simplified Technical English. Data: Earl (1983)
%   via earl_ref_data. One window at a time (re-opening brings it forward).
old = findall(groot, 'Type','figure', 'Tag','APAT_wave_help');
if ~isempty(old) && isvalid(old(1)), figure(old(1)); return; end

R = earl_ref_data();
pos = [100 80 900 760];
if nargin >= 1 && ~isempty(parent_fig) && isvalid(parent_fig)
    p = parent_fig.Position;
    pos = [p(1) + max(0,(p(3)-900)/2), p(2) + max(0,(p(4)-760)/2), 900, 760];
end
f = uifigure('Name','ABR Waves I–V — Help', 'Tag','APAT_wave_help', 'Position',pos, ...
    'Color',[1 1 1]);
h = uihtml(f, 'Position',[0 0 pos(3) pos(4)]);
h.HTMLSource = build_html(R);
f.AutoResizeChildren = 'off';
f.SizeChangedFcn = @(src,~) set(h, 'Position',[0 0 src.Position(3) src.Position(4)]);
end


