function svg = build_svg(R, CLR)
%BUILD_SVG  Idealized chinchilla click ABR at 70 dB SL (inline SVG for uihtml).
li  = find(R.sl == 70, 1);
W   = {'I','II','III','IV','V'};
AMP = [0.72 1.00 0.88 0.58 0.24];          % relative order of amplitude (Earl, text)
X0 = 60; X1 = 830; Y0 = 30; Y1 = 300; TMIN = 0; TMAX = 7;
sx = @(t) X0 + (t - TMIN) / (TMAX - TMIN) * (X1 - X0);
YMIN = -0.55; YMAX = 1.30;
sy = @(v) Y1 - (v - YMIN) / (YMAX - YMIN) * (Y1 - Y0);
mu = R.abs_mean(li,:);  lo = R.abs_min(li,:);  hi = R.abs_max(li,:);
ok = isfinite(mu);
pk_t = mu(ok);  pk_a = AMP(ok);  [pk_t, o] = sort(pk_t);  pk_a = pk_a(o);

% Trace: Gaussian peaks at the mean latencies, troughs between them, slow negative wave
tt = linspace(TMIN, TMAX, 561);  v = zeros(size(tt));
for k = 1:numel(pk_t)
    v = v + pk_a(k) * exp(-(tt - pk_t(k)).^2 / (2*0.13^2));
    if k < numel(pk_t), tr = (pk_t(k) + pk_t(k+1)) / 2; else, tr = pk_t(k) + 0.45; end
    v = v - 0.32 * pk_a(k) * exp(-(tt - tr).^2 / (2*0.12^2));
end
v = v - 0.22 * exp(-(tt - (pk_t(end) + 0.9)).^2 / (2*0.9^2));
v = v ./ (1 + exp(-(tt - 0.6) * 8));                       % flat before onset
d = sprintf('L%.1f,%.1f', [sx(tt); sy(v)]);  d(1) = 'M';

g = '';
for t = 0:TMAX                                               % grid + tick labels
    g = [g sprintf(['<line x1="%.1f" x2="%.1f" y1="%d" y2="%d" stroke="#eef1ef"/>' ...
        '<text x="%.1f" y="%d" text-anchor="middle" font-size="13" fill="#5d6763">%d</text>'], ...
        sx(t), sx(t), Y0, Y1, sx(t), Y1+20, t)]; %#ok<AGROW>
end
for k = find(ok)                                             % latency bands
    a = sx(lo(k));  b = sx(max(hi(k), lo(k) + 0.03));
    g = [g sprintf(['<rect x="%.1f" y="%d" width="%.1f" height="%d" fill="%s" fill-opacity="0.13"/>' ...
        '<line x1="%.1f" x2="%.1f" y1="%d" y2="%d" stroke="%s" stroke-opacity="0.5" stroke-dasharray="3 3"/>' ...
        '<line x1="%.1f" x2="%.1f" y1="%d" y2="%d" stroke="%s" stroke-opacity="0.5" stroke-dasharray="3 3"/>'], ...
        a, Y0, max(b-a,3), Y1-Y0, CLR{k}, a, a, Y0, Y1, CLR{k}, b, b, Y0, Y1, CLR{k})]; %#ok<AGROW>
end
g = [g sprintf('<line x1="%d" x2="%d" y1="%d" y2="%d" stroke="#1d2321"/><line x1="%d" x2="%d" y1="%d" y2="%d" stroke="#1d2321"/>', ...
    X0, X1, Y1, Y1, X0, X0, Y0, Y1)];
g = [g '<path d="' d '" fill="none" stroke="#1d2321" stroke-width="2.4" stroke-linejoin="round"/>'];
for k = find(ok)                                             % peak markers, labels, ranges
    x = sx(mu(k));  [~, i] = min(abs(tt - mu(k)));  y = sy(v(i));
    g = [g sprintf(['<circle cx="%.1f" cy="%.1f" r="6" fill="%s" stroke="#fff" stroke-width="2"/>' ...
        '<text x="%.1f" y="%.1f" text-anchor="middle" font-size="16" font-weight="700" fill="%s">%s</text>' ...
        '<text x="%.1f" y="%d" text-anchor="middle" font-size="12" fill="%s" font-family="Menlo,Consolas,monospace">%.2f–%.2f</text>'], ...
        x, y, CLR{k}, x, y-14, CLR{k}, W{k}, x, Y1-10-mod(k-1,2)*16, CLR{k}, lo(k), hi(k))]; %#ok<AGROW>
end
g = [g sprintf(['<text x="%.1f" y="%d" text-anchor="middle" font-size="14" font-weight="600" fill="#1d2321">Latency (ms) after click onset</text>' ...
    '<text x="18" y="%.1f" text-anchor="middle" font-size="14" font-weight="600" fill="#1d2321" transform="rotate(-90 18 %.1f)">Relative amplitude</text>' ...
    '<text x="%d" y="%d" font-size="12.5" fill="#5d6763">70 dB SL · band = latency range (ms) · marker = mean latency</text>'], ...
    (X0+X1)/2, Y1+44, (Y0+Y1)/2, (Y0+Y1)/2, X0, Y0-10)];
svg = ['<svg viewBox="0 0 850 350" style="width:100%;max-width:850px;height:auto;display:block;margin:6px 0" ' ...
       'xmlns="http://www.w3.org/2000/svg" font-family="-apple-system,Segoe UI,Helvetica,Arial,sans-serif" ' ...
       'role="img" aria-label="Ideal chinchilla ABR at 70 dB SL with Waves I to V">' g '</svg>'];
end


function s = ternary_s(c, a, b)
if c, s = a; else, s = b; end
end
